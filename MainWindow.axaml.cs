    private void OnBuildClick(object sender, RoutedEventArgs e)
    {
        var text = InputText.Text ?? "";

        // Разбиваем на слова (только буквы, сохраняем регистр для приоритета имён собственных)
        var words = Regex.Matches(text, @"[А-Яа-яЁё]+")
                         .Cast<Match>()
                         .Select(m => m.Value)
                         .Where(w => w.Length > 1)
                         .ToList();

        // Получаем основы и считаем частоты
        var freq = new Dictionary<string, int>();
        foreach (var word in words)
        {
            var stem = GetStem(word);
            if (freq.ContainsKey(stem))
                freq[stem]++;
            else
                freq[stem] = 1;
        }

        // Сортируем по убыванию, берём топ-20
        var top = freq.OrderByDescending(p => p.Value)
                      .Take(20)
                      .ToList();

        if (top.Count == 0) return;

        var maxCount = top.Max(p => p.Value);

        // Формируем данные для гистограммы
        var items = top.Select(p => new
        {
            Word = p.Key,
            Count = p.Value,
            BarWidth = (double)p.Value / maxCount * 300
        }).ToList();

        HistogramItems.ItemsSource = items;
    }

