    private static string GetStem(string word)
    {
        // Работаем в верхнем регистре, чтобы сравнивать с таблицами
        var upper = word.ToUpperInvariant();

        // --- Отбрасываем постфиксы "СЯ" и "СЬ" ---
        if (upper.EndsWith("СЯ")) upper = upper[..^2];
        else if (upper.EndsWith("СЬ")) upper = upper[..^2];

        // --- Ищем окончание от самого длинного к короткому ---
        // Сначала считаем n, длину основы по таблице:
        //   это длина слова после удаления постфиксов, но без удаления окончания.
        int n = upper.Length;

        // Теперь пытаемся отбросить окончание и получаем m.
        int m = n;
        string[] tables = { };

        // Проверяем от End5 к End1
        string[][] ordered = { End6, End5, End4, End3, End2, End1 };

        foreach (var table in ordered)
        {
            // Внутри таблицы тоже проверяем от длинных к коротким
            foreach (var end in table.OrderByDescending(x => x.Length))
            {
                if (upper.EndsWith(end) && upper.Length - end.Length > 1)
                {
                    m = upper.Length - end.Length;
                    goto done; // нашли самое длинное окончание, то выходим
                }
            }
        }

    done:
        // --- Берём более короткую форму: min(n, m) ---
        int stemLen = Math.Min(n, m);
        var stem = word[..stemLen];

        // Если важно сохранять регистр — word[..stemLen] вместо upper[..stemLen]
        return stem;
    }
